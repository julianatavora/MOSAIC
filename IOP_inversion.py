# ---------------------------------------------------------------------------
# Per-pixel inversion kernel
# ---------------------------------------------------------------------------

def _insider_inversion(rrs_pix, rrs_std_pix, wv, dim, temp_pix,
                        conv_criteria, bb_sea_water, a_phi, a_nap, a_cdom, bb_p_ori):
    """
    Core inversion for one pixel.

    Optimisations vs. original MATLAB:
      • V and D_perm (the system matrix) computed ONCE per pixel – they do not
        depend on temperature; only h changes between temp iterations.
      • Nested loops replaced by ndgrid-style vectorised index arrays.
      • All K=nSnap×nScdom×nY×nSf least-squares systems solved in a single
        batched normal-equation call (np.linalg.solve on stacked matrices).
      • IOP reconstruction fully vectorised over K combinations.
    """
    empty = lambda: (np.empty((0, len(wv))),) * 5 + (np.empty(0),) * 4 + (0,)

    if not np.any(~np.isnan(rrs_pix)):
        anap_c = acdom_c = bbp_c = bbpexp_c = np.empty((0, len(wv)))
        return (anap_c, np.empty(0), acdom_c, np.empty(0), bbp_c,
                np.empty(0), np.empty(0), np.nan, np.nan, np.empty(0), 0)

    L3, L4 = 0.0949, 0.0794

    Snap  = dim['Snap'];   nSnap  = len(Snap)
    Scdom = dim['Scdom'];  nScdom = len(Scdom)
    Y     = dim['Y'];      nY     = len(Y)
    Sf    = dim['Sf'];     nSf    = len(Sf)
    K     = nSnap * nScdom * nY * nSf
    N_wv  = len(wv)

    # ------------------------------------------------------------------
    # Precompute per-pixel quantities (independent of temperature)
    # ------------------------------------------------------------------
    ii_g, mm_g, nn_g, gg_g = np.meshgrid(
        np.arange(nSnap), np.arange(nScdom), np.arange(nY), np.arange(nSf),
        indexing='ij')
    ii_vec = ii_g.ravel();  mm_vec = mm_g.ravel()
    nn_vec = nn_g.ravel();  gg_vec = gg_g.ravel()

    Bmat_snap  = Snap[ii_vec]
    Bmat_scdom = Scdom[mm_vec]
    Bmat_Y     = Y[nn_vec]

    V, _ = _v(L3, L4, rrs_pix)           # [N_wv]
    bb_p  = bb_p_ori * V                  # [nY × N_wv]

    a_nap_all  = a_nap[ii_vec]            # [K × N_wv]
    a_cdom_all = a_cdom[mm_vec]
    bb_p_all   = bb_p[nn_vec]
    a_phi_all  = a_phi[gg_vec]

    # D_perm: [K × N_wv × 4]  →  one [N_wv × 4] system per combination
    D_perm = np.stack([a_nap_all, a_cdom_all, bb_p_all, a_phi_all], axis=2)  # [K×N_wv×4]

    # Precompute normal-equation matrices (temperature-independent)
    # DtD[k] = D[k]^T D[k]   shape [K × 4 × 4]
    DtD = np.einsum('kia,kib->kab', D_perm, D_perm)   # [K × 4 × 4]

    # Accumulators
    anap_cum = [];  acdom_cum = [];  bbp_cum = [];  bbpexp_cum = []
    aphyt_cum = [];  eanap_cum = [];  eacdom_cum = [];  ebbp_cum = []
    temp_cum = [];   N_cum = []

    # ------------------------------------------------------------------
    # Temperature loop – only h (and therefore DtH) changes
    # ------------------------------------------------------------------
    for q in range(len(temp_pix)):
        a_sea_water = _asw_corr(float(temp_pix[q]), wv)
        h_col       = _Array_h(a_sea_water, bb_sea_water, V)   # [N_wv]

        # DtH[k] = D[k]^T h   shape [K × 4]
        DtH = np.einsum('kia,i->ka', D_perm, h_col)

        # Batch solve K systems: DtD[k] x[k] = DtH[k]
        with warnings.catch_warnings():
            warnings.simplefilter('ignore')
            p_all = np.linalg.solve(DtD, DtH)          # [K × 4]
        p_matrix = p_all.T                              # [4 × K]

        # Physical-constraint filter
        ok = (p_matrix[0] > -0.002) & (p_matrix[1] > -0.002) & \
             (p_matrix[2] > -0.002) & (p_matrix[3] > -0.002)
        B = np.where(ok)[0]

        num_valid = 0
        if B.size > 0:
            # Vectorised IOP reconstruction [K × N_wv]
            A_nap  = p_matrix[0, :, None] * a_nap_all
            A_cdom = p_matrix[1, :, None] * a_cdom_all
            B_bp   = p_matrix[2, :, None] * bb_p_all / V   # remove V scaling
            A_phi  = p_matrix[3, :, None] * a_phi_all

            a_total = A_nap + A_cdom + a_sea_water + A_phi  # [K × N_wv]
            b_total = B_bp  + bb_sea_water                  # [K × N_wv]

            bb_ov_ab  = b_total[B] / (a_total[B] + b_total[B])
            rrs_model = L3 * bb_ov_ab + L4 * bb_ov_ab**2

            # Convergence check
            rrs_row  = rrs_pix[None, :]
            criteria = np.maximum(conv_criteria * rrs_row,
                                  0.001 * (wv >= 700).astype(float))
            valid_mask = np.all(np.abs(rrs_model - rrs_row) < criteria, axis=1)
            valid_B    = B[valid_mask]
            num_valid  = valid_B.size

            if num_valid > 0:
                anap_cum.append(A_nap[valid_B])
                acdom_cum.append(A_cdom[valid_B])
                bbp_cum.append(B_bp[valid_B])
                bbpexp_cum.append(bb_p_ori[nn_vec[valid_B]])   # no V scaling
                D3 = a_phi_all[valid_B]
                aphyt_cum.append(np.nanmean(A_phi[valid_B] / D3, axis=1))
                eanap_cum.append(Bmat_snap[valid_B])
                eacdom_cum.append(Bmat_scdom[valid_B])
                ebbp_cum.append(Bmat_Y[valid_B])
                temp_cum.append(np.full(num_valid, float(temp_pix[q])))
        N_cum.append(num_valid)

    # ------------------------------------------------------------------
    # Concatenate across all temperature iterations
    # ------------------------------------------------------------------
    def vcat(lst):
        return np.concatenate(lst, axis=0) if lst else np.empty((0, N_wv))

    anap_c   = vcat(anap_cum);   acdom_c  = vcat(acdom_cum)
    bbp_c    = vcat(bbp_cum);    bbpexp_c = vcat(bbpexp_cum)
    aphyt_c  = np.concatenate(aphyt_cum) if aphyt_cum else np.empty(0)
    eanap_c  = np.concatenate(eanap_cum) if eanap_cum else np.empty(0)
    eacdom_c = np.concatenate(eacdom_cum) if eacdom_cum else np.empty(0)
    ebbp_c   = np.concatenate(ebbp_cum)  if ebbp_cum  else np.empty(0)
    temp_c   = np.concatenate(temp_cum)  if temp_cum  else np.empty(0)
    N_total  = int(np.sum(N_cum))

    # ------------------------------------------------------------------
    # SPM estimation
    # ------------------------------------------------------------------
    SPM_val = np.nan;  SPM_unc_val = np.nan
    if N_total > 0 and bbpexp_c.size > 0:
        bbp700_grid = np.arange(0.002, 0.027, 0.002)           # [13]
        bb_p_grid   = bbpexp_c[:, :, None] * bbp700_grid       # [N × N_wv × 13]
        if np.any(~np.isnan(bb_p_grid)):
            SPM_model = bbp_c[:, :, None] / bb_p_grid          # [N × N_wv × 13]
            W         = _weight_asses_field(rrs_std_pix, rrs_pix, wv)
            spm_mean  = np.nanmean(SPM_model, axis=(0, 2))     # [N_wv]
            SPM_val   = float(np.nansum(spm_mean * W) / np.nansum(W))
            spm_84    = np.nanpercentile(SPM_model, 84, axis=(0, 2))
            spm_16    = np.nanpercentile(SPM_model, 16, axis=(0, 2))
            SPM_max   = float(np.nansum(spm_84 * W) / np.nansum(W))
            SPM_min   = float(np.nansum(spm_16 * W) / np.nansum(W))
            SPM_unc_val = float(np.nanmean([SPM_max, SPM_min])) / np.sqrt(5)

    return (anap_c, eanap_c, acdom_c, eacdom_c, bbp_c, ebbp_c,
            aphyt_c, SPM_val, SPM_unc_val, temp_c, N_total)


# ---------------------------------------------------------------------------
# Main function
# ---------------------------------------------------------------------------

def IOP_inversion(RW, RW_std, wavelength, conv_criteria, temp,
                  n_jobs=1, checkpoint_file='results_checkpoint.npz',
                  checkpoint_cadence=50):
    """
    IOP inversion for remote-sensing reflectance.

    Parameters
    ----------
    RW, RW_std   : ndarray, shape [nspectra × nwl] or [nrow × ncol × nwl]
    wavelength   : 1-D array, wavelengths in nm
    conv_criteria: float, relative convergence tolerance
    temp         : ndarray, sea-surface temperature (same spatial dims as RW)
    n_jobs       : int, number of parallel workers for 3-D case (−1 = all CPUs)
    checkpoint_file, checkpoint_cadence : rolling save options for 3-D case

    Returns
    -------
    dict with keys: anap_model_mean/error, acdom_model_mean/error,
                    bbp_model_mean/error, aphyt_model_mean/error,
                    Sanap/Sacdom/Ybbp _mean/error, SPM, SPM_unc,
                    temp, temp_unc, nn
    """
    warnings.filterwarnings('ignore')
    wavelength = np.asarray(wavelength, dtype=float).ravel()

    actual_dims = np.squeeze(RW).ndim

    if actual_dims == 2:
        mask = (wavelength >= 650) & (wavelength <= 850) & \
               ~((wavelength >= 745) & (wavelength <= 773))
        wavelength = wavelength[mask]
        RW     = RW[:, mask];   RW_std = RW_std[:, mask]
    else:
        mask = (wavelength >= 650) & (wavelength <= 850)
        wavelength = wavelength[mask]
        RW     = RW[:, :, mask];   RW_std = RW_std[:, :, mask]

    rrs     = (RW / np.pi)     / (0.52 + 1.7 * (RW / np.pi))
    rrs_std = (RW_std / np.pi) / (0.52 + 1.7 * (RW_std / np.pi))

    # Pre-build eigenvector grids (shared across all pixels)
    bb_sea_water = 0.0037 * (380**4.32) / (wavelength**4.32)
    a_phi = _phyto_avg_field(wavelength)          # [5 × N_wv]
    Sf    = np.ones(a_phi.shape[0])

    Snap  = np.arange(0.001, 0.013, 0.002)
    Scdom = np.arange(0.002, 0.017, 0.002)
    Y     = np.arange(0.0,   1.61,  0.1)

    a_nap = np.array([(np.exp(-s*(wavelength - 443)) -
                        np.exp(-s*(850 - 443))) + 0.0072
                       for s in Snap])             # [nSnap × N_wv]
    a_cdom = np.array([np.exp(-s*(wavelength - 440))
                        for s in Scdom])           # [nScdom × N_wv]
    bb_p   = np.array([(700.0/wavelength)**y for y in Y])  # [nY × N_wv]

    dim = dict(Snap=Snap, Scdom=Scdom, Sf=Sf, Y=Y)

    # -----------------------------------------------------------------------
    # 2-D case: simple loop over spectra
    # -----------------------------------------------------------------------
    if actual_dims == 2:
        nspec = rrs.shape[0]
        res = {k: np.full(nspec, np.nan) for k in
               ['anap_model_mean','acdom_model_mean','bbp_model_mean',
                'aphyt_model_mean','Sanap_model_mean','Sacdom_model_mean',
                'Ybbp_model_mean','SPM','temp','nn',
                'anap_model_error','acdom_model_error','bbp_model_error',
                'aphyt_model_error','Sanap_model_error','Sacdom_model_error',
                'Ybbp_model_error','SPM_unc','temp_unc']}

        for ii in range(nspec):
            id_ok  = ~np.isnan(rrs[ii])
            rrs_px = rrs[ii, id_ok]
            std_px = rrs_std[ii, id_ok]
            wv     = wavelength[id_ok]
            tp     = float(temp[ii]) if np.ndim(temp) >= 1 else float(temp)
            temp_pix = np.array([tp]) if not np.isnan(tp) else np.arange(5, 35, dtype=float)

            if rrs_px.size == 0:
                print(f'{ii+1}/{nspec}')
                continue

            (anap_m, S_anap, acdom_m, S_acdom, bbp_m, Y_bbp,
             aphyt, SPM, SPM_unc, temp_m, N) = _insider_inversion(
                rrs_px, std_px, wv, dim, temp_pix, conv_criteria,
                bb_sea_water[id_ok], a_phi[:, id_ok],
                a_nap[:, id_ok], a_cdom[:, id_ok], bb_p[:, id_ok])

            if N > 0:
                ap_slope, ap443, ap_slope_std, ap443_std = \
                    _get_AP_coeff_slope(wv, anap_m, S_anap)
                acd_slope, acd440, acd_slope_std, acd440_std = \
                    _get_ACDOM_coeff_slope(wv, acdom_m, S_acdom)
                bp_slope, bp700, bp_slope_std, bp700_std = \
                    _get_BBP_coeff_slope(wv, bbp_m, Y_bbp)

                res['anap_model_mean'][ii]    = ap443
                res['acdom_model_mean'][ii]   = acd440
                res['bbp_model_mean'][ii]     = bp700
                res['aphyt_model_mean'][ii]   = float(np.nanmean(aphyt))
                res['nn'][ii]                 = N
                res['Sanap_model_mean'][ii]   = ap_slope
                res['Sacdom_model_mean'][ii]  = acd_slope
                res['Ybbp_model_mean'][ii]    = bp_slope
                res['SPM'][ii]                = SPM
                res['temp'][ii]               = float(np.nanmean(temp_m))

                res['anap_model_error'][ii]   = ap443_std
                res['acdom_model_error'][ii]  = acd440_std
                res['bbp_model_error'][ii]    = bp700_std
                res['aphyt_model_error'][ii]  = float(np.nanstd(aphyt, ddof=0))
                res['Sanap_model_error'][ii]  = ap_slope_std
                res['Sacdom_model_error'][ii] = acd_slope_std
                res['Ybbp_model_error'][ii]   = bp_slope_std
                res['SPM_unc'][ii]            = SPM_unc
                res['temp_unc'][ii]           = float(np.nanstd(temp_m, ddof=0))

            print(f'{ii+1}/{nspec}')

        return res

    # -----------------------------------------------------------------------
    # 3-D case: parallel over rows (joblib), with checkpoint saves
    # -----------------------------------------------------------------------
    nrow, ncol = rrs.shape[:2]
    res = {k: np.full((nrow, ncol), np.nan) for k in
           ['anap_model_mean','acdom_model_mean','bbp_model_mean',
            'aphyt_model_mean','Sanap_model_mean','Sacdom_model_mean',
            'Ybbp_model_mean','SPM','temp','nn',
            'anap_model_error','acdom_model_error','bbp_model_error',
            'aphyt_model_error','Sanap_model_error','Sacdom_model_error',
            'Ybbp_model_error','SPM_unc','temp_unc']}

    # Fallback temp range for NaN-temp pixels
    temp_flat = np.asarray(temp).ravel()
    if np.any(~np.isnan(temp_flat)):
        tm = round(float(np.nanmean(temp_flat)))
        ts = round(float(np.nanstd(temp_flat, ddof=1)))
        temp_nan_fallback = np.arange(tm - ts, tm + ts + 1, dtype=float)
    else:
        temp_nan_fallback = np.arange(5, 35, dtype=float)

    def _process_pixel(ii, jj):
        id_ok  = ~np.isnan(rrs[ii, jj])
        rrs_px = rrs[ii, jj, id_ok]
        std_px = rrs_std[ii, jj, id_ok]
        wv     = wavelength[id_ok]
        tp     = float(temp[ii, jj])
        temp_pix = np.array([tp]) if not np.isnan(tp) else temp_nan_fallback

        if rrs_px.size == 0:
            return ii, jj, None

        out = _insider_inversion(
            rrs_px, std_px, wv, dim, temp_pix, conv_criteria,
            bb_sea_water[id_ok], a_phi[:, id_ok],
            a_nap[:, id_ok], a_cdom[:, id_ok], bb_p[:, id_ok])
        return ii, jj, out

    def _fill_result(res, ii, jj, out):
        if out is None:
            return
        (anap_m, S_anap, acdom_m, S_acdom, bbp_m, Y_bbp,
         aphyt, SPM, SPM_unc, temp_m, N) = out
        if N == 0:
            return

        wv = wavelength[~np.isnan(rrs[ii, jj])]
        ap_slope, ap443, ap_slope_std, ap443_std = \
            _get_AP_coeff_slope(wv, np.nanmean(anap_m, 0, keepdims=True),
                                np.array([np.nanmean(S_anap)]))
        acd_slope, acd440, acd_slope_std, acd440_std = \
            _get_ACDOM_coeff_slope(wv, np.nanmean(acdom_m, 0, keepdims=True),
                                   np.array([np.nanmean(S_acdom)]))
        bp_slope, bp700, bp_slope_std, bp700_std = \
            _get_BBP_coeff_slope(wv, np.nanmean(bbp_m, 0, keepdims=True),
                                 np.array([np.nanmean(Y_bbp)]))

        res['anap_model_mean'][ii,jj]    = ap443
        res['acdom_model_mean'][ii,jj]   = acd440
        res['bbp_model_mean'][ii,jj]     = bp700
        res['aphyt_model_mean'][ii,jj]   = float(np.nanmean(aphyt))
        res['nn'][ii,jj]                 = N
        res['Sanap_model_mean'][ii,jj]   = ap_slope
        res['Sacdom_model_mean'][ii,jj]  = acd_slope
        res['Ybbp_model_mean'][ii,jj]    = bp_slope
        res['SPM'][ii,jj]                = SPM
        res['temp'][ii,jj]               = float(np.nanmean(temp_m))
        res['anap_model_error'][ii,jj]   = ap443_std
        res['acdom_model_error'][ii,jj]  = acd440_std
        res['bbp_model_error'][ii,jj]    = bp700_std
        res['aphyt_model_error'][ii,jj]  = float(np.nanstd(aphyt, ddof=0))
        res['Sanap_model_error'][ii,jj]  = ap_slope_std
        res['Sacdom_model_error'][ii,jj] = acd_slope_std
        res['Ybbp_model_error'][ii,jj]   = bp_slope_std
        res['SPM_unc'][ii,jj]            = SPM_unc
        res['temp_unc'][ii,jj]           = float(np.nanstd(temp_m, ddof=0))

    if n_jobs == 1:
        for jj in range(ncol - 1, -1, -1):
            for ii in range(nrow - 1, -1, -1):
                _, _, out = _process_pixel(ii, jj)
                _fill_result(res, ii, jj, out)
            print(f'{ncol - jj}/{ncol}')
            if (ncol - jj) % checkpoint_cadence == 0:
                np.savez(checkpoint_file, **res)
                print(f'  checkpoint saved → {checkpoint_file}')
    else:
        # Parallel execution via joblib
        try:
            from joblib import Parallel, delayed
        except ImportError:
            raise ImportError("Install joblib for parallel processing:  pip install joblib")

        tasks = [(ii, jj) for jj in range(ncol - 1, -1, -1)
                           for ii in range(nrow - 1, -1, -1)]
        results_list = Parallel(n_jobs=n_jobs, prefer='threads')(
            delayed(_process_pixel)(ii, jj) for ii, jj in tasks)

        for k, (ii, jj, out) in enumerate(results_list):
            _fill_result(res, ii, jj, out)
            if (k + 1) % (nrow * checkpoint_cadence) == 0:
                np.savez(checkpoint_file, **res)
                print(f'  checkpoint saved → {checkpoint_file}')

    return res

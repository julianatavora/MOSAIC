def _get_AP_coeff_slope(nm, anap_all, Sanap_all):
    anap  = np.nanmean(anap_all, axis=0)
    Sanap = float(np.nanmean(Sanap_all))
    offset_band  = 850.0
    ap_NIRoffset = 0.0072

    def model(x):
        return x[1] * (np.exp(-x[0]*(nm - 443)) - np.exp(-x[0]*(offset_band - 443))) + ap_NIRoffset
    cost = lambda x: np.sum((model(x) - anap)**2)
    x0   = [Sanap, float(np.max(anap))]
    with warnings.catch_warnings():
        warnings.simplefilter('ignore')
        x_opt = fmin(cost, x0, xtol=1e-8, ftol=1e-8, disp=False)

    ap_slope = x_opt[0];  ap443 = x_opt[1]
    ap_slope_std = float(np.nanstd(Sanap_all, ddof=0))
    if anap_all.ndim > 1 and anap_all.shape[0] > 1:
        f = interp1d(nm, np.nanstd(anap_all, axis=0, ddof=0),
                     kind='linear', fill_value='extrapolate')
        ap443_std = float(f(443))
    else:
        f = interp1d(nm, np.atleast_1d(anap_all).ravel(),
                     kind='linear', fill_value='extrapolate')
        ap443_std = float(f(443))
    return ap_slope, ap443, ap_slope_std, ap443_std



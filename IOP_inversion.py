def _v(L3, L4, Rrs):
    """One positive root of the Rrs-IOP relationship (Wang, Boss & Roesler 2005)."""
    x = (-L3 + np.sqrt(L3**2 + 4.0 * L4 * Rrs)) / (2.0 * L4)
    V = 1.0 - 1.0 / x
    return V, x


def _Array_h(a_sea_water, bb_sea_water, V):
    """RHS vector for the linear inversion system."""
    # All inputs are 1-D arrays of length N_wv
    return -(a_sea_water + bb_sea_water * V)


def _asw_corr(temp_pix, nm_touse):
    """Temperature-corrected pure-water absorption (Pope & Fry 97, Lou)."""
    f_asw  = interp1d(_NM_SAMPLE, _ASW,   kind='linear', fill_value='extrapolate')
    f_psiT = interp1d(_NM_SAMPLE, _PSI_T, kind='linear', fill_value='extrapolate')
    return f_asw(nm_touse) + f_psiT(nm_touse) * (temp_pix - 22.0)


def _phyto_avg_field(wavelength):
    """Interpolate phytoplankton absorption eigenvectors to requested wavelengths."""
    wl = np.arange(400, 851, dtype=float)
    # normalise at 400 nm
    a_f_norm = _A_F / _A_F[:, [0]]
    a_phi = np.zeros((a_f_norm.shape[0], len(wavelength)))
    for i in range(a_f_norm.shape[0]):
        f = interp1d(wl, a_f_norm[i], kind='linear', fill_value='extrapolate')
        a_phi[i] = f(wavelength)
    return a_phi


def _weight_asses_field(error, rrs, nm):
    """Per-wavelength uncertainty weights for SPM retrieval."""
    relative = np.sqrt(2.0) * 0.05 * rrs
    if np.isscalar(error) and np.isnan(error):
        kernel   = np.ones(10) / 10.0
        smoothed = np.convolve(rrs, kernel, mode='same')
        absolute = np.full(len(nm), np.nanstd(np.abs(smoothed - rrs)))
    else:
        absolute = np.asarray(error, dtype=float).ravel()
    max_noise = np.maximum(absolute, relative)
    W = 1.0 / max_noise
    return W / np.max(W)


